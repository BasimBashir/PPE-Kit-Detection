"""Measure event → dashboard latency (NFR-PERF-005) with a real browser session on the camera wall.

  uv run --no-project --with playwright python scripts/benchmark/ui_latency.py --minutes 10
The dashboard acknowledges each new event after painting it (requestAnimationFrame); the API stores
`dashboard_rendered_at`. This script keeps the wall open (realistic preview polling load), then reads every event
persisted during the session and reports persisted → rendered latency. Browser and server share the host clock.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[2]
sys.stdout.reconfigure(encoding="utf-8")
BASE = "http://127.0.0.1:8000"


def pw() -> str:
    return next(line.split("=", 1)[1].strip() for line in (ROOT / ".env").read_text(encoding="utf-8").splitlines()
                if line.startswith("PPE_ADMIN_PASSWORD="))


def api(path: str, token: str | None = None, body: dict | None = None) -> dict:
    req = urllib.request.Request(BASE + path, data=json.dumps(body).encode() if body else None,
                                 method="POST" if body else "GET",
                                 headers={"Content-Type": "application/json",
                                          **({"Authorization": f"Bearer {token}"} if token else {})})
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.loads(r.read())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--minutes", type=float, default=10)
    ap.add_argument("--channel", default="msedge")
    a = ap.parse_args()
    started = datetime.now(UTC)
    with sync_playwright() as p:
        b = p.chromium.launch(channel=a.channel, headless=True)
        page = b.new_page(viewport={"width": 1600, "height": 1000})
        page.goto(BASE + "/login")
        page.get_by_label("Username").fill("admin")
        page.get_by_label("Password").fill(pw())
        page.get_by_role("button", name="Sign in").click()
        page.wait_for_url(BASE + "/")
        page.goto(BASE + "/cameras")
        deadline = time.time() + a.minutes * 60
        while time.time() < deadline:
            page.wait_for_timeout(5000)
        b.close()
    token = api("/api/v1/auth/login", body={"username": "admin", "password": pw()})["access_token"]
    since = started.isoformat().replace("+00:00", "Z")
    lat, total, offset = [], 0, 0
    while True:
        page_ = api(f"/api/v1/events?since={since}&limit=200&offset={offset}", token)
        total = page_["total"]
        lat += [e["latency"]["persist_to_dashboard_s"] for e in page_["items"]
                if e["latency"]["persist_to_dashboard_s"] is not None]
        offset += 200
        if offset >= total:
            break
    lat.sort()

    def pct(q: float) -> float | None:
        return round(lat[min(len(lat) - 1, int(q * len(lat)))], 3) if lat else None

    res = {"session_minutes": a.minutes, "events_persisted_during_session": total, "events_with_render_ack": len(lat),
           "persist_to_dashboard_s": {"p50": pct(0.5), "p95": pct(0.95), "max": lat[-1] if lat else None,
                                      "mean": round(statistics.mean(lat), 3) if lat else None},
           "target": "< 1 s (NFR-PERF-005)", "client": f"headless {a.channel} on the camera wall (10 live previews)"}
    md = ["# Event → dashboard latency (generated by scripts/benchmark/ui_latency.py)", "",
          "Boundary: event row committed in PostgreSQL (`persisted_at`) → new event painted in the browser (client ack "
          "after requestAnimationFrame, `dashboard_rendered_at`). Path: outbox claim → WebSocket `event_created` → "
          "React render. Same host clock for browser and server.", "", "```json", json.dumps(res, indent=1), "```"]
    (ROOT / "docs" / "benchmarks" / "ui_latency.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(json.dumps(res, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
